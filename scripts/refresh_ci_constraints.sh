#!/bin/bash
# Regenerate requirements/ci-constraints.txt: the exact versions CI installs.
#
# Resolves the newest versions inside pyproject.toml's ranges in a throwaway
# venv (no inherited site-packages), freezes them, then runs the full suite in
# that same venv. The suite checks the candidate file itself, so it is put in
# place first; if anything fails the previous file is restored, so the
# constraints never name versions that were not tested here.
#
#   scripts/refresh_ci_constraints.sh [python3.12]
set -euo pipefail
cd "$(dirname "$0")/.."
PYTHON=${1:-python3.12}
TARGET=requirements/ci-constraints.txt
WORK=$(mktemp -d)
mkdir -p requirements
if [ -f "$TARGET" ]; then cp "$TARGET" "$WORK/previous.txt"; fi
restore() {
  status=$?
  if [ "$status" -ne 0 ]; then
    if [ -f "$WORK/previous.txt" ]; then cp "$WORK/previous.txt" "$TARGET"; else rm -f "$TARGET"; fi
    echo "FAILED (exit $status): $TARGET left unchanged" >&2
  fi
  rm -rf "$WORK"
}
trap restore EXIT

"$PYTHON" -m venv "$WORK/venv"
VPY="$WORK/venv/bin/python"
"$VPY" -m pip install -q --upgrade pip wheel setuptools
"$VPY" -m pip install -q -e ".[test,optimization]"
{
  echo "# Exact versions installed by CI (pip install -c requirements/ci-constraints.txt)."
  echo "# Generated by scripts/refresh_ci_constraints.sh on $(date -u +%F) with $("$VPY" --version);"
  echo "# the full test suite passed on exactly these versions. Do not edit by hand."
  "$VPY" -m pip freeze --all --exclude-editable | LC_ALL=C sort -f
} > "$TARGET"
# Same conditions as the CI runner: UTC, no inherited environment.
env -i HOME="$WORK" PATH="$WORK/venv/bin:/usr/bin:/bin" LANG=C.UTF-8 TZ=UTC CI=true \
  python -m pytest tests/ -q -p no:cacheprovider
echo "updated $TARGET"
